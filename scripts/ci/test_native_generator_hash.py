#!/usr/bin/env python3
"""Self-test for scripts/ci/native_generator_hash.py.

Builds throwaway fixture trees; touches nothing in the repository. The point is
that the checker itself fails when it should: a CRLF checkout must not change the
hash, a real content change must, and non-reproducible content must be rejected.

Usage: python3 scripts/ci/test_native_generator_hash.py
"""
from __future__ import annotations

import contextlib
import importlib.util
import io
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
SPEC = importlib.util.spec_from_file_location("native_generator_hash", HERE / "native_generator_hash.py")
assert SPEC and SPEC.loader
hashcheck = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(hashcheck)

PIN = "v0.8.4-0.20261108220316-c4197b7fe562"
GO_HEADER = (
    "// Code generated by mygo generate from the interfaces of the native module. DO NOT EDIT.\n"
    "// mygo:native 2 006d88f0942bea95\n\npackage runs\n\nvar _module = 1\n"
)
RUST_HEADER = (
    "// Code generated by mygo generate from the interfaces of the native module. DO NOT EDIT.\n"
    "// mygo:native 2 006d88f0942bea95\n\npub const MODULE: &str = \"Runs\";\n"
)

CASES: list[tuple[str, callable]] = []


def case(fn):
    CASES.append((fn.__name__, fn))
    return fn


def build_tree(root: Path) -> None:
    files = {
        "prototypes/mygo-run/go.mod": (
            "module asterlab-mygo-prototype\n\ngo 1.27.3\n\n"
            f"require (\n\tgithub.com/egoist/mygo {PIN}\n)\n"
        ),
        "prototypes/mygo-run/go.sum": f"github.com/egoist/mygo {PIN} h1:fixture\n",
        "scripts/mygo-native-linux.sh": f'#!/usr/bin/env bash\nmygo_pin="{PIN}"\n',
        "scripts/mygo-build.ps1": f"$mygoPin = '{PIN}'\n",
        "prototypes/mygo-run/modules/runs/runs.go": "package runs\n\ntype RunService interface{}\n",
        "prototypes/mygo-run/modules/runs/rust/Cargo.toml": "[package]\nname = \"runs\"\n",
        "prototypes/mygo-run/modules/runs/rust/src/lib.rs": "mod mygo;\n",
        "prototypes/mygo-run/modules/runs/runs_native.go": GO_HEADER,
        "prototypes/mygo-run/modules/runs/rust/src/mygo.rs": RUST_HEADER,
    }
    for rel, text in files.items():
        target = root / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")


def run_cli(root: Path, *args: str) -> int:
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        code = hashcheck.main(["--root", str(root), *args])
    run_cli.last = out.getvalue() + err.getvalue()  # type: ignore[attr-defined]
    return code


@case
def canonical_bytes_normalises_line_endings() -> None:
    lf, drift = hashcheck.canonical_bytes(b"a\nb\n")
    assert drift == [], drift
    crlf, drift = hashcheck.canonical_bytes(b"a\r\nb\r\n")
    assert crlf == lf and drift == ["crlf"], (crlf, drift)
    cr, drift = hashcheck.canonical_bytes(b"a\rb\r")
    assert cr == lf and drift == ["cr"], (cr, drift)
    bom, drift = hashcheck.canonical_bytes(b"\xef\xbb\xbfa\n")
    assert bom == b"a\n" and drift == ["utf8-bom"], (bom, drift)


@case
def canonical_bytes_keeps_content_differences() -> None:
    assert hashcheck.canonical_bytes(b"a\n")[0] != hashcheck.canonical_bytes(b"a \n")[0]
    assert hashcheck.sha256(hashcheck.canonical_bytes(b"a\n")[0]) != hashcheck.sha256(
        hashcheck.canonical_bytes(b"a\r\nb\n")[0]
    )


@case
def volatile_findings_flags_each_source() -> None:
    for text in (
        "const built = '2026-11-13'\n",
        "const built = 1762992000\n",
        "let path = \"C:\\\\Users\\\\runner\\\\runs.go\";\n",
        "let path = \"\\\\\\\\server\\\\share\\\\runs.go\";\n",
        "let path = \"/home/runner/runs.go\";\n",
    ):
        findings = hashcheck.volatile_findings(text)
        assert findings, f"not flagged: {text!r}"
    assert hashcheck.volatile_findings(GO_HEADER) == []
    assert hashcheck.volatile_findings(RUST_HEADER) == []


@case
def pins_must_agree() -> None:
    texts = {
        "go.mod": f"require github.com/egoist/mygo {PIN}\n",
        "linux script": f'mygo_pin="{PIN}"\n',
        "windows script": f"$mygoPin = '{PIN}'\n",
    }
    assert hashcheck.pins_from_texts(texts)["go.mod"] == PIN

    texts["windows script"] = "$mygoPin = 'v0.8.3'\n"
    try:
        hashcheck.pins_from_texts(texts)
    except hashcheck.CheckError as exc:
        assert "disagrees" in str(exc), exc
    else:
        raise AssertionError("a floating pin was accepted")

    del texts["linux script"]
    try:
        hashcheck.pins_from_texts(texts)
    except hashcheck.CheckError as exc:
        assert "no MyGo version pin" in str(exc), exc
    else:
        raise AssertionError("a missing pin was accepted")


@case
def headers_must_agree() -> None:
    fmt, iface = hashcheck.parse_headers({"a.go": GO_HEADER, "b.rs": RUST_HEADER})
    assert (fmt, iface) == (2, "006d88f0942bea95"), (fmt, iface)

    try:
        hashcheck.parse_headers({"a.go": GO_HEADER, "b.rs": RUST_HEADER.replace("006d88f0", "106d88f0")})
    except hashcheck.CheckError as exc:
        assert "disagree" in str(exc), exc
    else:
        raise AssertionError("differing interface hashes were accepted")

    try:
        hashcheck.parse_headers({"a.go": "package runs\n"})
    except hashcheck.CheckError as exc:
        assert "no '// mygo:native" in str(exc), exc
    else:
        raise AssertionError("a missing header was accepted")


@case
def compare_reports_every_difference() -> None:
    a = {
        "input_sha256": "a",
        "output_sha256": "b",
        "files": {"f": "c"},
        "generator": {"module": "m", "pin": "p", "format": 2, "interface_hash": "i"},
    }
    b = {
        "input_sha256": "a",
        "output_sha256": "b2",
        "files": {"f": "c2"},
        "generator": {"module": "m", "pin": "p2", "format": 2, "interface_hash": "i"},
    }
    problems = hashcheck.compare(a, b)
    assert any("output_sha256" in p for p in problems), problems
    assert any("f:" in p for p in problems), problems
    assert any("generator.pin" in p for p in problems), problems
    assert hashcheck.compare(a, a) == []


@case
def checkout_line_endings_do_not_change_the_hash() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        build_tree(root)
        assert run_cli(root, "--update-golden") == 0, getattr(run_cli, "last", "")
        golden = hashcheck.load_golden(root / hashcheck.GOLDEN)
        lf_output = golden["output_sha256"]

        for rel in hashcheck.GENERATED:
            path = root / rel
            path.write_bytes(path.read_bytes().replace(b"\n", b"\r\n"))

        code = run_cli(root, "--check")
        assert code == 0, getattr(run_cli, "last", "")
        assert "drift crlf" in getattr(run_cli, "last", ""), getattr(run_cli, "last", "")
        assert hashcheck.load_golden(root / hashcheck.GOLDEN)["output_sha256"] == lf_output


@case
def content_changes_fail_the_check() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        build_tree(root)
        assert run_cli(root, "--update-golden") == 0, getattr(run_cli, "last", "")

        path = root / hashcheck.GENERATED[0]
        path.write_text(GO_HEADER.replace("var _module = 1", "var _module = 2"), encoding="utf-8", newline="\n")
        code = run_cli(root, "--check")
        assert code == 1, getattr(run_cli, "last", "")
        assert "drift" in getattr(run_cli, "last", ""), getattr(run_cli, "last", "")


@case
def volatile_generated_content_fails_even_when_golden_matches() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        build_tree(root)
        path = root / hashcheck.GENERATED[1]
        path.write_text(RUST_HEADER + 'pub const BUILT: &str = "2026-11-13";\n', encoding="utf-8", newline="\n")
        assert run_cli(root, "--update-golden") == 1, getattr(run_cli, "last", "")
        assert "cannot be identical on two platforms" in getattr(run_cli, "last", "")


@case
def missing_golden_is_an_input_error() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        build_tree(root)
        assert run_cli(root, "--check") == 2, getattr(run_cli, "last", "")


def main() -> int:
    failed = 0
    for name, fn in CASES:
        try:
            fn()
        except AssertionError as exc:
            failed += 1
            print(f"FAIL {name}: {exc}")
        else:
            print(f"ok   {name}")
    print(f"selftest: {len(CASES) - failed}/{len(CASES)} passed")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
